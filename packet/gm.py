"""
Gauss-Manin connection on the isotypic piece V[chi_A] of H^4_prim(X_t) for a
one-parameter family F_t = F_base + t * Cdir, computed by Griffiths-Dwork reduction
over F_p[u]/(u^N) with t = t0 + u.  Outputs the rank of the sub-local-system
generated by [A Omega/F^2] and its Hodge numbers.
"""
import sys, itertools, random
from flint import nmod_mat
from cert import char, char_add, unit, monoms_char, NV, PRIME

P = 268435399
N_ORDER = 24  # truncation order in u

# ---------- polynomials with power-series coefficients: dict exps -> list of N coeffs ----------
def ps_zero():
    return [0] * N_ORDER

def ps_add(a, b):
    return [(x + y) % P for x, y in zip(a, b)]

def ps_scale(a, c):
    return [(x * c) % P for x in a]

def ps_deriv(a):
    # d/du
    return [((i + 1) * a[i + 1]) % P for i in range(N_ORDER - 1)] + [0]

def ps_is_zero(a):
    return all(x == 0 for x in a)


class Family:
    def __init__(self, F_base_terms, Cdir_terms, chiP, t0):
        """F_base_terms, Cdir_terms: dict exps->int.  chiP: character of the numerator polynomials P."""
        self.Fb = F_base_terms
        self.C = Cdir_terms
        self.t0 = t0 % P
        self.chiP = chiP
        self.Ft = dict(F_base_terms)
        for e, c in Cdir_terms.items():
            self.Ft[e] = (self.Ft.get(e, 0) + self.t0 * c) % P
        self.dF = [self._deriv(self.Ft, i) for i in range(NV)]
        self.dC = [self._deriv(Cdir_terms, i) for i in range(NV)]
        self.cache = {}

    @staticmethod
    def _deriv(poly, i):
        out = {}
        for e, c in poly.items():
            if e[i] > 0:
                e2 = list(e); e2[i] -= 1
                out[tuple(e2)] = (out.get(tuple(e2), 0) + c * e[i]) % P
        return {e: c for e, c in out.items() if c}

    @staticmethod
    def _mul_mono(poly, e, c=1):
        out = {}
        for e1, c1 in poly.items():
            e2 = tuple(a + b for a, b in zip(e1, e))
            out[e2] = (out.get(e2, 0) + c1 * c) % P
        return out

    def setup_degree(self, deg):
        """Precompute reduction data for numerators of degree deg (= 6k-6 for pole order k... used for Q of degree 6k)."""
        if deg in self.cache:
            return self.cache[deg]
        rows = monoms_char(deg, self.chiP)
        ridx = {m: i for i, m in enumerate(rows)}
        nr = len(rows)
        # columns: (i, m) with m of degree deg-5, char(m) = chiP + e_i
        cols = []
        colsC = []
        for i in range(NV):
            chm = char_add(self.chiP, unit(i))
            for m in monoms_char(deg - 5, chm):
                q = self._mul_mono(self.dF[i], m)
                qc = self._mul_mono(self.dC[i], m)
                cols.append((i, m, {ridx[e]: c for e, c in q.items()}))
                colsC.append({ridx[e]: c for e, c in qc.items()})
        nc = len(cols)
        M0 = nmod_mat(nr, nc, P)
        for j, (_, _, col) in enumerate(cols):
            for r, c in col.items():
                M0[r, j] = c
        # complement of column space: rows not hit by pivots of rref(M0^T)
        R, rank = M0.transpose().rref()
        pivots = []
        for r in range(rank):
            for c in range(nr):
                if R[r, c] != 0:
                    pivots.append(c); break
        comp = [r for r in range(nr) if r not in set(pivots)]
        # square-ish full-row-rank system [M0 | E_comp]
        ncol2 = nc + len(comp)
        Maug = nmod_mat(nr, ncol2, P)
        for j, (_, _, col) in enumerate(cols):
            for r, c in col.items():
                Maug[r, j] = c
        for k, r in enumerate(comp):
            Maug[r, nc + k] = 1
        # pseudo-inverse via rref of [Maug | I]
        big = nmod_mat(nr, ncol2 + nr, P)
        for r in range(nr):
            for j in range(ncol2):
                big[r, j] = Maug[r, j]
            big[r, ncol2 + r] = 1
        Rb, rk = big.rref()
        assert rk == nr, (deg, rk, nr)
        # For each row r of Rb: pivot column piv(r) < ncol2; solution x[piv(r)] = (Rb[r, ncol2:]) . b
        piv = []
        for r in range(nr):
            for j in range(ncol2):
                if Rb[r, j] != 0:
                    piv.append(j); break
        Tsolve = [[int(Rb[r, ncol2 + s]) for s in range(nr)] for r in range(nr)]  # x[piv[r]] = sum_s Tsolve[r][s] b[s]
        data = dict(rows=rows, ridx=ridx, cols=cols, colsC=colsC, comp=comp, piv=piv, Tsolve=Tsolve, nc=nc, nr=nr)
        self.cache[deg] = data
        return data

    def reduce_once(self, Qps, deg):
        """Q (dict exps -> ps) of degree deg.  Returns (NF as dict exps->ps restricted to comp rows,
        divs = sum_i d(Q_i)/dx_i as dict exps->ps of degree deg-6)."""
        dat = self.setup_degree(deg)
        nr, nc, comp, piv, Tsolve = dat['nr'], dat['nc'], dat['comp'], dat['piv'], dat['Tsolve']
        ridx = dat['ridx']
        # b(u) as nr x N array
        b = [[0] * N_ORDER for _ in range(nr)]
        for e, ps in Qps.items():
            b[ridx[e]] = list(ps)
        # solve (M0' + u M1') x = b order by order: M1' acts on the first nc coords (Q_i part)
        x = [[0] * N_ORDER for _ in range(nc + len(comp))]
        for n in range(N_ORDER):
            # rhs_n = b_n - M1' x_{n-1}
            rhs = [b[r][n] for r in range(nr)]
            if n > 0:
                for j in range(nc):
                    xj = x[j][n - 1]
                    if xj:
                        for r, c in dat['colsC'][j].items():
                            rhs[r] = (rhs[r] - c * xj) % P
            for r in range(nr):
                s = 0
                Tr = Tsolve[r]
                for sidx in range(nr):
                    if rhs[sidx]:
                        s += Tr[sidx] * rhs[sidx]
                x[piv[r]][n] = s % P
        NF = {}
        for k, r in enumerate(comp):
            ps = x[nc + k]
            if not ps_is_zero(ps):
                NF[dat['rows'][r]] = ps
        divs = {}
        for j in range(nc):
            ps = x[j]
            if ps_is_zero(ps):
                continue
            i, m, _ = dat['cols'][j]
            if m[i] > 0:
                e2 = list(m); e2[i] -= 1; e2 = tuple(e2)
                divs[e2] = ps_add(divs.get(e2, ps_zero()), ps_scale(ps, m[i]))
        return NF, divs

    def normalize(self, cls):
        """cls: dict k -> (dict exps->ps) numerator of pole order k.  Reduce to normal forms."""
        out = {}
        pending = {k: dict(v) for k, v in cls.items()}
        while pending:
            k = max(pending.keys())
            Q = pending.pop(k)
            if not Q:
                continue
            deg = 6 * (k - 1)
            if deg == 0:
                pass
                continue
            NF, divs = self.reduce_once(Q, deg)
            if NF:
                out[k] = NF
            if divs and k - 1 >= 1:
                inv = pow(k - 1, P - 2, P)
                lower = pending.setdefault(k - 1, {})
                for e, ps in divs.items():
                    lower[e] = ps_add(lower.get(e, ps_zero()), ps_scale(ps, inv))
        return out

    def nabla(self, cls):
        """Gauss-Manin derivative d/dt of a normalized class."""
        new = {}
        for k, Q in cls.items():
            # [dQ/du Omega/F^k]
            for e, ps in Q.items():
                d = ps_deriv(ps)
                if not ps_is_zero(d):
                    tgt = new.setdefault(k, {})
                    tgt[e] = ps_add(tgt.get(e, ps_zero()), d)
            # -k [Q C Omega/F^{k+1}]
            tgt = new.setdefault(k + 1, {})
            for e, ps in Q.items():
                for ec, cc in self.C.items():
                    e2 = tuple(a + b for a, b in zip(e, ec))
                    tgt[e2] = ps_add(tgt.get(e2, ps_zero()), ps_scale(ps, (-k * cc) % P))
        return self.normalize(new)

    def coords(self, cls):
        """Constant-term coordinate vector (at u=0) in the complement bases of degrees 6, 12, 18."""
        vec = []
        for k in (2, 3, 4):
            dat = self.setup_degree(6 * (k - 1))
            Q = cls.get(k, {})
            for r in dat['comp']:
                ps = Q.get(dat['rows'][r])
                vec.append(ps[0] if ps else 0)
        return vec

    def dims(self):
        return [len(self.setup_degree(6 * (k - 1))['comp']) for k in (2, 3, 4)]


def rank_mod(vectors):
    if not vectors:
        return 0
    M = nmod_mat(len(vectors), len(vectors[0]), P)
    for i, v in enumerate(vectors):
        for j, x in enumerate(v):
            if x: M[i, j] = x
    return M.rank()


def run(F_base, Cdir, A_exps, t0, label, maxj=22):
    chiP = char(A_exps)
    fam = Family(F_base, Cdir, chiP, t0)
    dims = fam.dims()
    print(f"[{label}] t0={t0}: Hodge dims of block (h31,h22,h13) = {dims}", flush=True)
    cls = {sum(A_exps) // 6 + 1: {tuple(A_exps): [1] + [0] * (N_ORDER - 1)}}
    cls = fam.normalize(cls)
    vecs = [fam.coords(cls)]
    ranks = [1]
    cur = cls
    for j in range(1, maxj):
        cur = fam.nabla(cur)
        vecs.append(fam.coords(cur))
        r = rank_mod(vecs)
        ranks.append(r)
        if r == ranks[-2] and j >= 2:
            break
    rA = ranks[-1]
    # Hodge numbers of the generated sub-local-system at t0: W = span(vecs); F^3 = coords in degree-6 block only, etc.
    n1, n2, n3 = dims
    W = vecs
    def dim_cap(mask_len):
        # dim of W ∩ {last mask_len coordinates zero}
        # = dim W - rank of projection of W onto those coordinates
        proj = [v[len(v) - mask_len:] for v in W]
        return rA - rank_mod(proj) if mask_len > 0 else rA
    f3 = dim_cap(n2 + n3)
    f2 = dim_cap(n3)
    print(f"[{label}] rank sequence {ranks}; rank of local system generated by [A] = {rA}; "
          f"Hodge numbers of W: h31={f3}, h22={f2 - f3}, h13={rA - f2}", flush=True)
    return rA, vecs


